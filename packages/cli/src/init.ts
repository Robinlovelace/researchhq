/**
 * Scaffold a fresh ResearchHQ workspace in targetDir. Errors when the target
 * already contains a researchhq.config.yaml unless options.force is set.
 */
export function initInstance(targetDir: string, options: InitOptions = {}): InitResult {
  const configPath = join(targetDir, 'researchhq.config.yaml');
  if (existsSync(configPath) && !options.force) {
    throw new Error(
      `${configPath} already exists; pass --force (or run init in a fresh directory) to overwrite`,
    );
  }

  mkdirSync(join(targetDir, 'data'), { recursive: true });
  mkdirSync(join(targetDir, 'public-data'), { recursive: true });

  const files: string[] = [
    configPath,
    join(targetDir, 'data', 'planned-papers.yaml'),
    join(targetDir, 'data', 'journal-metrics.yaml'),
    join(targetDir, 'data', 'overrides.yaml'),
    join(targetDir, '.gitignore'),
    join(targetDir, 'README.md'),
  ];

  writeFileSync(configPath, configYaml(options), 'utf8');
  writeFileSync(files[1], plannedPapersYaml(options), 'utf8');
  writeFileSync(files[2], journalMetricsYaml(), 'utf8');
  writeFileSync(files[3], overridesYaml(), 'utf8');
  writeFileSync(files[4], gitignore(), 'utf8');
  writeFileSync(files[5], readme(), 'utf8');

  return { dir: targetDir, files };
}
