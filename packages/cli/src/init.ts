/**
 * ResearchHQ init: scaffold a fresh ResearchHQ user workspace so any
 * researcher can adopt the pipeline with `npx @researchhq/cli init`.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { stringify as stringifyYaml } from 'yaml';

export interface InitOptions {
  name?: string;
  role?: string;
  affiliation?: string;
  orcid?: string;
  /** Overwrite an existing workspace instead of erroring. */
  force?: boolean;
}

export interface InitResult {
  dir: string;
  files: string[];
}

function currentYear(): number {
  return new Date().getFullYear();
}

/**
 * Serialize researchhq.config.yaml through the safe yaml stringifier so
 * quotes, backslashes, and other special characters in author name,
 * affiliation, or ORCID values are escaped correctly.
 */
function configYaml(options: InitOptions): string {
  const name = options.name ?? 'Your Name';
  const role = options.role ?? 'Researcher';
  const affiliation = options.affiliation ?? 'Your University';
  const orcid = options.orcid ?? '0000-0000-0000-0000';
  const header =
    '# ResearchHQ configuration (generated by @researchhq/cli init)\n' +
    '# Rule: no em-dashes anywhere in this file.\n';
  const data = {
    author: {
      name,
      role,
      affiliation,
      orcid,
    },
    // Harvesting settings for `researchhq sync`
    sync: {
      orcid,
      minYear: 2000,
      excludeTypes: ['paratext', 'erratum'],
    },
    // Repository-relative paths consumed by the CLI and dashboard build
    paths: {
      plannedPapers: 'data/planned-papers.yaml',
      journalMetrics: 'data/journal-metrics.yaml',
      overrides: 'data/overrides.yaml',
      publicExport: 'public-data/portfolio.public.json',
    },
  };
  return header + stringifyYaml(data);
}

